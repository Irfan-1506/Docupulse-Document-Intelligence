"""Pydantic v2 schemas for financial data validation and cross-verification."""

from __future__ import annotations

from enum import Enum
from typing import Any, Dict, List, Literal, Optional, Union
from pydantic import BaseModel, ConfigDict, Field


class ValidationSeverity(str, Enum):
    """Severity classification for validation issues."""
    ERROR = "ERROR"
    WARNING = "WARNING"
    INFO = "INFO"


class ValidationRuleCode(str, Enum):
    """Distinct validation rule identifiers aligned with the frontend HITL workbench."""
    MISSING_REQUIRED_FIELD = "MISSING_REQUIRED_FIELD"
    INVALID_NUMERIC_VALUE = "INVALID_NUMERIC_VALUE"
    LINE_ITEMS_SUM_MISMATCH = "LINE_ITEMS_SUM_MISMATCH"
    SUBTOTAL_TAX_TOTAL_MISMATCH = "SUBTOTAL_TAX_TOTAL_MISMATCH"
    LINE_ITEM_MATH_ERROR = "LINE_ITEM_MATH_ERROR"
    EXACT_DUPLICATE_INVOICE = "EXACT_DUPLICATE_INVOICE"
    FUZZY_DUPLICATE_INVOICE = "FUZZY_DUPLICATE_INVOICE"
    LOW_EXTRACTION_CONFIDENCE = "LOW_EXTRACTION_CONFIDENCE"
    CROSS_VERIFY_AMOUNT_VARIANCE = "CROSS_VERIFY_AMOUNT_VARIANCE"
    CROSS_VERIFY_MISSING_IN_LEDGER = "CROSS_VERIFY_MISSING_IN_LEDGER"
    CROSS_VERIFY_DATE_OR_VENDOR_MISMATCH = "CROSS_VERIFY_DATE_OR_VENDOR_MISMATCH"


class ValidationIssue(BaseModel):
    """Individual diagnostic finding generated by financial validation rules."""
    model_config = ConfigDict(extra="ignore")

    rule_code: ValidationRuleCode = Field(
        ...,
        description="Standardized rule identifier.",
    )
    severity: ValidationSeverity = Field(
        ...,
        description="Severity level (ERROR, WARNING, INFO).",
    )
    field_name: Optional[str] = Field(
        default=None,
        description="Field primarily associated with the issue.",
    )
    message: str = Field(
        ...,
        description="Human-readable diagnostic description for UI display.",
    )
    expected_value: Optional[Union[str, float]] = Field(
        default=None,
        description="Mathematically or logically expected value.",
    )
    actual_value: Optional[Union[str, float]] = Field(
        default=None,
        description="Actual value present on the record.",
    )
    variance: Optional[float] = Field(
        default=None,
        description="Numerical variance between actual and expected values.",
    )


class CrossVerificationMatch(BaseModel):
    """Detailed reconciliation output comparing a primary document record to a reference."""
    model_config = ConfigDict(extra="ignore")

    source_record_id: str = Field(
        ...,
        description="ID of the source invoice record being verified (e.g. PDF Invoice ID).",
    )
    target_reference_id: str = Field(
        ...,
        description="Identifier of matching target reference (e.g., spreadsheet row or secondary PDF ID).",
    )
    verification_type: Literal["PDF_TO_EXCEL", "PDF_TO_PDF"] = Field(
        ...,
        description="Modality of cross-verification.",
    )
    match_status: Literal["EXACT_MATCH", "VARIANCE_DETECTED", "UNMATCHED_ORPHAN"] = Field(
        ...,
        description="Terminal matching status.",
    )
    matched_on_keys: List[str] = Field(
        default_factory=list,
        description="Keys used to establish linkage (e.g. ['invoice_number', 'supplier_name']).",
    )
    field_deltas: Dict[str, Dict[str, Any]] = Field(
        default_factory=dict,
        description="Detailed discrepancy map: field -> {'source': val1, 'target': val2, 'delta': diff}.",
    )
    confidence_score: float = Field(
        default=1.0,
        description="Confidence score for the match between 0.0 and 1.0.",
        ge=0.0,
        le=1.0,
    )


class RecordValidationResult(BaseModel):
    """Validation outcome for a single invoice record."""
    model_config = ConfigDict(extra="ignore")

    record_id: str = Field(
        ...,
        description="ID of the evaluated invoice record.",
    )
    source_document_id: str = Field(
        ...,
        description="ID of the parent document from Task 1.",
    )
    invoice_number: Optional[str] = Field(
        default=None,
        description="Extracted invoice number.",
    )
    is_valid: bool = Field(
        ...,
        description="True if record is error-free, passes all strict financial rules, and has no unresolved duplicates.",
    )
    validation_status: Literal["AUTO_VERIFIED", "MANUALLY_VERIFIED", "NEEDS_MANUAL_REVIEW", "REJECTED_DUPLICATE"] = Field(
        ...,
        description="High-level processing status for HITL workflow.",
    )
    requires_manual_review: bool = Field(
        ...,
        description="Flag alerting that human intervention is required before downstream approval.",
    )
    issues: List[ValidationIssue] = Field(
        default_factory=list,
        description="List of all detected issues, warnings, and informational diagnostics.",
    )
    cross_verification: Optional[CrossVerificationMatch] = Field(
        default=None,
        description="Reconciliation match result if cross-verification was executed.",
    )
    computed_metrics: Dict[str, Optional[float]] = Field(
        default_factory=dict,
        description="Computed financial metrics (e.g., computed_line_sum, computed_total, total_variance).",
    )


class BatchValidationReport(BaseModel):
    """Aggregate summary report for a batch of validated records."""
    model_config = ConfigDict(extra="ignore")

    total_records_evaluated: int = Field(
        default=0,
        description="Total number of invoice records evaluated in this batch.",
        ge=0,
    )
    auto_verified_count: int = Field(
        default=0,
        description="Count of records passing without any errors or warnings.",
        ge=0,
    )
    manual_review_count: int = Field(
        default=0,
        description="Count of records flagged for Human-in-the-Loop review.",
        ge=0,
    )
    duplicate_count: int = Field(
        default=0,
        description="Count of duplicate invoice records detected.",
        ge=0,
    )
    cross_verified_exact_matches: int = Field(
        default=0,
        description="Count of cross-verification exact reconciliations.",
        ge=0,
    )
    cross_verified_variances: int = Field(
        default=0,
        description="Count of cross-verification matches with variances detected.",
        ge=0,
    )
    results: List[RecordValidationResult] = Field(
        default_factory=list,
        description="Detailed validation results for each individual record.",
    )


class ValidationConfig(BaseModel):
    """Configuration governing validation rules, tolerances, and thresholds."""
    model_config = ConfigDict(extra="ignore")

    rounding_tolerance: float = Field(
        default=0.02,
        description="Permissible financial arithmetic discrepancy tolerance in currency units.",
        ge=0.0,
    )
    fuzzy_supplier_threshold: float = Field(
        default=0.85,
        description="Minimum string similarity ratio (0.0 to 1.0) to consider two vendor names identical.",
        ge=0.0,
        le=1.0,
    )
    auto_verify_confidence_threshold: float = Field(
        default=0.75,
        description="Minimum extraction confidence required for automatic verification.",
        ge=0.0,
        le=1.0,
    )
    required_fields: List[str] = Field(
        default_factory=lambda: ["invoice_number", "invoice_date", "supplier_name", "total", "currency"],
        description="Strictly required fields; absence triggers ERROR severity.",
    )
    recommended_fields: List[str] = Field(
        default_factory=lambda: ["subtotal", "tax", "customer_name"],
        description="Recommended fields; absence triggers WARNING severity.",
    )
